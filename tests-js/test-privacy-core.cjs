const assert=require('node:assert/strict');
const core=require('../extension/core/privacy-core.js');
const original='My name is Nila Rao. Contact nila@example.org; PAN ABCDE1234F.';
const model=[{type:'person',text:'Nila Rao',start:original.indexOf('Nila Rao'),end:original.indexOf('Nila Rao')+8,necessary:false,reason:'Not required.'}];
const es=core.mergeDetected(original,model);
assert.equal(es.length,3,'model NER and generic formats should combine');
assert.deepEqual(es.map(e=>e.type),['PERSON','EMAIL','PAN']);
assert.equal(es.every(e=>e.necessary===false),true);
const s=core.newSession();
const p=core.prepare(s,{text:original,entities:es},{});
assert.doesNotMatch(p.sanitized_text,/Nila Rao|nila@example.org|ABCDE1234F/);
assert.equal(p.replacements,3);
assert.equal(Object.keys(s.dummyToReal).length,3);
const r=core.restore(s,p.sanitized_text);
assert.equal(r.text,original);
assert.equal(r.unresolved,false);
const p2=core.prepare(s,{text:original,entities:es},{});
assert.equal(p.sanitized_text,p2.sanitized_text,'consistent tokens for repeat values');
const other=core.newSession();
assert.notEqual(core.prepare(other,{text:original,entities:es},{}).sanitized_text,p.sanitized_text,'independent sessions');
const dup='Call nila@example.org or nila@example.org';
const found=core.detectFormats(dup);
assert.equal(found.length,2);
const rd=core.prepare(s,{text:dup,entities:core.spansFor(dup,found)},{});
assert.equal(rd.sanitized_text.match(/PRIVATE_EMAIL/g).length,2);
assert.equal(core.restore(s,'[PRIVATE_EMAIL_999_ABCDEF]').unresolved,true);
assert.throws(()=>core.prepare(s,{text:original,entities:es},{e1:{mode:'EXACT'}}),/necessity review/);
const dob='My birthday is 10 July 2004';
const de=[{type:'DOB',text:'10 July 2004',start:15,end:27,id:'e1',necessary:true,reason:'Age accuracy'}];
const sy=core.newSession();
const dt=core.prepare(sy,{text:dob,entities:de},{e1:{mode:'YEAR'}});
assert.match(dt.sanitized_text,/birth year 2004/);
assert.doesNotMatch(dt.sanitized_text,/10 July/);
assert.throws(()=>core.prepare(sy,{text:dob,entities:de},{e1:{mode:'RANGE'}}),/Ranges only/);
assert.deepEqual(core.spansFor('abc',[{text:'secret',start:0,end:6,type:'SECRET'}]),[],'hallucinated offsets discarded');
assert.equal(core.mergeDetected('My PAN is ABCDE1234F',[]).length,1,'regex supplements local model');
console.log('PASS: local engine detection validation, isolation, consent, pseudonymization and restoration');
