'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../extension');
const content=fs.readFileSync(path.join(root,'content/content.js'),'utf8');
const html=fs.readFileSync(path.join(root,'private/frame.html'),'utf8');
const frame=fs.readFileSync(path.join(root,'private/frame.js'),'utf8');
const css=fs.readFileSync(path.join(root,'private/frame.css'),'utf8');
assert.match(content,/privateComposer\.style\.display='none';[\s\S]*?showReenableFrame\(\);/, 'OFF must hide private composer instead of only collapsing its content');
assert.match(content,/restoreNativeContainer\(hiddenComposer\);[\s\S]*?privateComposer\.style\.display='none'/,'OFF must restore native textbox before hiding private input');
assert.match(content,/function showReenableFrame\(\)/);
assert.match(content,/document\.documentElement\.appendChild\(reenableFrame\)/,'small switch needs top-level placement outside native input');
assert.match(content,/rect\.top-height-6/,'small switch should sit outside, above the website searchbar');
assert.match(content,/function showPrivateComposer\(\)/);
assert.match(content,/privateComposer\.style\.display='block'/,'ON must restore protected private composer');
assert.match(content,/hideNativeContainer\(hiddenComposer\);\s*showPrivateComposer\(\)/,'ON must hide native editor and restore privacy');
assert.match(content,/if\(!protectionEnabled\)\{privateComposer\.style\.display='none';showReenableFrame\(\);\}/,'remount must keep OFF mode intact');
assert.match(html,/id="off-toggle"/);
assert.match(html,/id="reenable-protection"/);
assert.match(frame,/else if\(mode==='off-toggle'\)initOffToggle\(\)/);
assert.match(frame,/type:'SET_PROTECTION_ENABLED',enabled:true/);
assert.match(frame,/type==='PRIVACY_SHIELD_REACTIVATED'/);
assert.match(css,/#off-toggle\{/);
assert.doesNotMatch(content.slice(content.indexOf('function showReenableFrame(){'),content.indexOf('function showPrivateComposer(){')),/\bdraft\b|\btext\b\s*:/,'no user draft in OFF switch creation');
console.log('PASS: OFF hides entire extension composer; native searchbar visible and mini switch re-enables without raw draft copying');
